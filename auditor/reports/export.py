import csv
import html
import json
from pathlib import Path
from typing import Any

from ..security.validators import redact_pii, sanitize_csv_value


def safe_audit_summary(audit: dict) -> dict:
    """Keep export metadata/scores, but omit raw text, free-form evidence, and excerpts."""
    dimensions = audit.get("dimension_scores") or []
    escalation = audit.get("escalation") or {}
    policy_refs = audit.get("policy_refs") or []
    summary = {
        key: audit.get(key)
        for key in (
            "id",
            "case_id",
            "category",
            "overall_score",
            "decision",
            "evaluation_mode",
            "evaluator_model",
            "confidence",
            "hard_stop_triggered",
            "config_snapshot",
            "created_at",
        )
        if key in audit
    }
    summary["dimension_scores"] = [
        {key: item.get(key) for key in ("dimension", "score", "confidence") if key in item}
        for item in dimensions
    ]
    summary["escalation"] = {
        key: escalation.get(key)
        for key in ("expected", "actual", "correct", "verdict", "urgency", "destination")
        if key in escalation
    }
    summary["policy_refs"] = [
        {
            key: item.get(key)
            for key in ("policy_id", "version", "section", "relevance")
            if key in item
        }
        for item in policy_refs
    ]

    def redact(value):
        if isinstance(value, str):
            return redact_pii(value)
        if isinstance(value, list):
            return [redact(item) for item in value]
        if isinstance(value, dict):
            return {key: redact(item) for key, item in value.items()}
        return value

    return redact(summary)


def safe_audit_summaries(audits: list[dict]) -> list[dict]:
    return [safe_audit_summary(audit) for audit in audits]


def export_csv(audits: list[dict[str, Any]], path: Path):
    if not audits:
        return
    # flatten dimension scores
    fieldnames = [
        "case_id",
        "overall_score",
        "decision",
        "evaluation_mode",
        "escalation.verdict",
        "hard_stop_triggered",
    ] + [
        f"dim_{d}"
        for d in [
            "factual_accuracy",
            "completeness",
            "policy_compliance",
            "hallucination",
            "resolution_guidance",
            "tone_clarity",
            "privacy_safety",
            "escalation",
            "actionability",
        ]
    ]
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fieldnames)
        w.writeheader()
        for a in audits:
            row = {
                "case_id": sanitize_csv_value(str(a.get("case_id", ""))),
                "overall_score": a.get("overall_score", ""),
                "decision": a.get("decision", ""),
                "evaluation_mode": a.get("evaluation_mode", ""),
                "escalation.verdict": (a.get("escalation") or {}).get("verdict", ""),
                "hard_stop_triggered": a.get("hard_stop_triggered", ""),
            }
            for dim in [
                "factual_accuracy",
                "completeness",
                "policy_compliance",
                "hallucination",
                "resolution_guidance",
                "tone_clarity",
                "privacy_safety",
                "escalation",
                "actionability",
            ]:
                # dimension_scores is list
                sc_map = {d["dimension"]: d["score"] for d in a.get("dimension_scores", [])}
                row[f"dim_{dim}"] = sc_map.get(dim, "")
            # sanitize
            row = {
                k: sanitize_csv_value(str(v)) if isinstance(v, str) else v for k, v in row.items()
            }
            w.writerow(row)


def export_json(audits: list[dict], path: Path):
    Path(path).write_text(json.dumps(safe_audit_summaries(audits), indent=2), encoding="utf-8")


def export_html(audits: list[dict], path: Path, title="Audit Report"):
    rows = ""
    for a in audits:
        dims = " ".join(f"{d['dimension']}:{d['score']}" for d in a.get("dimension_scores", []))
        rows += f"<tr><td>{html.escape(str(a.get('case_id', '')))}</td><td>{a.get('overall_score')}</td><td>{html.escape(a.get('decision', ''))}</td><td>{html.escape(dims)}</td></tr>"
    h = f"""<!doctype html><html><head><meta charset="utf-8"><title>{html.escape(title)}</title>
    <style>body{{font-family:Inter,Arial,sans-serif;margin:32px;color:#1a1a1a}}table{{border-collapse:collapse;width:100%}}th,td{{border:1px solid #ddd;padding:8px;text-align:left}}th{{background:#0f172a;color:#fff}}h1{{color:#0f172a}}</style>
    </head><body><h1>{html.escape(title)}</h1><p>Generated by AI Customer Support Response Quality Auditor</p><table><tr><th>Case ID</th><th>Score</th><th>Decision</th><th>Dimensions</th></tr>{rows}</table></body></html>"""
    Path(path).write_text(h, encoding="utf-8")
